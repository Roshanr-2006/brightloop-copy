// Invoices list (owner: Swathy).
import { Link, useNavigate, useSearchParams } from 'react-router-dom';
import useList from '../../hooks/useList';
import {
  Card, DataTable, ErrorBanner, PageHeader, Pagination, SearchInput, StatusBadge, Tabs, Toolbar,
} from '../../components/ui';
import { formatDate, formatMoney } from '../../utils/format';

const TABS = [
  { value: '', label: 'All', key: 'all' },
  { value: 'draft', label: 'Draft', key: 'draft' },
  { value: 'confirmed', label: 'Confirmed', key: 'confirmed' },
  { value: 'overdue', label: 'Overdue', key: 'overdue' },
  { value: 'paid', label: 'Paid', key: 'paid' },
  { value: 'cancelled', label: 'Cancelled', key: 'cancelled' },
];

export default function InvoiceList() {
  const navigate = useNavigate();
  const [query] = useSearchParams();
  const list = useList('/invoices', {
    status: query.get('status') || (query.get('overdue') === '1' ? 'overdue' : ''),
    search: '',
    from: '',
    to: '',
    customer_id: query.get('customer') || '',
    subscription_id: query.get('subscription') || '',
  });
  const counts = list.data.counts || {};

  const columns = [
    { key: 'number', label: 'Number', render: (r) => <Link to={`/invoices/${r.id}`} onClick={(e) => e.stopPropagation()}><strong>{r.number}</strong></Link> },
    { key: 'customer_name', label: 'Customer' },
    {
      key: 'subscription_number',
      label: 'Subscription',
      render: (r) => (r.subscription_id
        ? <Link to={`/subscriptions/${r.subscription_id}`} onClick={(e) => e.stopPropagation()}>{r.subscription_number}</Link>
        : '-'),
    },
    { key: 'invoice_date', label: 'Date', render: (r) => formatDate(r.invoice_date) },
    {
      key: 'due_date',
      label: 'Due',
      render: (r) => <span style={r.is_overdue ? { color: 'var(--danger)', fontWeight: 600 } : undefined}>{formatDate(r.due_date)}</span>,
    },
    { key: 'total_amount', label: 'Total', align: 'right', render: (r) => formatMoney(r.total_amount) },
    {
      key: 'balance_due',
      label: 'Balance',
      align: 'right',
      render: (r) => (r.status === 'cancelled' ? <span className="muted">-</span> : formatMoney(r.balance_due)),
    },
    {
      key: 'status',
      label: 'Status',
      render: (r) => (
        <>
          <StatusBadge status={r.is_overdue ? 'overdue' : r.status} />
          {r.sent_at && <span className="muted" style={{ fontSize: 12, marginLeft: 6 }}>sent</span>}
        </>
      ),
    },
  ];

  return (
    <>
      <PageHeader
        title="Invoices"
        subtitle="Generated by the billing run from active subscriptions"
        actions={<Link className="btn primary" to="/billing">Run billing</Link>}
      />
      <Card>
        <Tabs
          tabs={TABS.map((t) => ({ value: t.value, label: t.label, count: counts[t.key] }))}
          value={list.params.status}
          onChange={(v) => list.setParam('status', v)}
        />
        <Toolbar>
          <SearchInput value={list.params.search} onChange={(v) => list.setParam('search', v)} placeholder="Search number or customer" />
          <span className="row" style={{ alignItems: 'center', gap: 6 }}>
            <span className="muted">Invoice date</span>
            <input type="date" className="input" aria-label="From date" title="From" value={list.params.from} onChange={(e) => list.setParam('from', e.target.value)} />
            <span className="muted">to</span>
            <input type="date" className="input" aria-label="To date" title="To" value={list.params.to} min={list.params.from || undefined} onChange={(e) => list.setParam('to', e.target.value)} />
          </span>
          {(list.params.from || list.params.to || list.params.customer_id || list.params.subscription_id) && (
            <button
              type="button"
              className="btn ghost sm"
              onClick={() => list.setParams((p) => ({ ...p, from: '', to: '', customer_id: '', subscription_id: '', page: 1 }))}
            >
              Clear filters
            </button>
          )}
        </Toolbar>
        <ErrorBanner error={list.error} />
        <DataTable
          columns={columns}
          rows={list.data.items}
          loading={list.loading}
          empty="No invoices match these filters"
          onRowClick={(r) => navigate(`/invoices/${r.id}`)}
        />
        <Pagination page={list.data.page} pages={list.data.pages} total={list.data.total} onChange={list.setPage} />
      </Card>
    </>
  );
}
